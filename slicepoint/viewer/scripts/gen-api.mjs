#!/usr/bin/env node
// Generate the live viewer's API types from the committed slicepoint-api OpenAPI document.
//
//   node scripts/gen-api.mjs           write src/live/api.generated.ts
//   node scripts/gen-api.mjs --check   exit 1 if the committed file is stale
//
// Source of truth: slicepoint/api/openapi.json (itself generated from the FastAPI app by
// `uv run --directory api slicepoint-api-openapi`; the API's tests fail if it is stale).
// Mirrors gen-contract.mjs. Only the live build imports these types.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = resolve(root, "../api/openapi.json");
const outPath = resolve(root, "src/live/api.generated.ts");
const check = process.argv.includes("--check");

const specText = readFileSync(specPath, "utf8");
const sha256 = createHash("sha256").update(specText).digest("hex");
const source = relative(root, specPath);
const banner =
  `// GENERATED by scripts/gen-api.mjs from ${source} (sha256 ${sha256}).\n` +
  "// Do not edit. Run `pnpm gen:api` after openapi.json changes; `pnpm check:api` fails on drift.\n" +
  "/* eslint-disable */\n";

const spec = JSON.parse(specText);
const ast = await openapiTS(spec, { alphabetize: true, immutable: true });
// Validation constants the start form mirrors (the server validates again).
const req = spec?.components?.schemas?.AssessmentRequest?.properties ?? {};
const sitePattern = req.site_id?.pattern;
const siteNameMax = req.site_name?.anyOf?.find((s) => s.type === "string")?.maxLength;
if (typeof sitePattern !== "string" || typeof siteNameMax !== "number") {
  console.error("gen-api: AssessmentRequest.site_id pattern or site_name maxLength not found in openapi.json");
  process.exit(2);
}
const consts =
  `\nexport const SITE_ID_PATTERN = ${JSON.stringify(sitePattern)};\n` +
  `export const SITE_NAME_MAX_LENGTH = ${siteNameMax};\n`;
const text = banner + astToString(ast) + consts;

if (check) {
  if (!existsSync(outPath) || readFileSync(outPath, "utf8") !== text) {
    console.error(
      `API type drift: src/live/api.generated.ts does not match ${source}.\n` +
        "Run `pnpm gen:api` and review the change.",
    );
    process.exit(1);
  }
  console.log(`API types up to date (openapi.json sha256 ${sha256.slice(0, 12)}).`);
} else {
  writeFileSync(outPath, text);
  console.log(`Wrote ${relative(root, outPath)}.`);
}

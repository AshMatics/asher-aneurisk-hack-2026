#!/usr/bin/env node
// Generate the viewer's contract artefacts from the slicepoint-schemas JSON Schema.
//
//   node scripts/gen-contract.mjs           write src/contract/*.generated.*
//   node scripts/gen-contract.mjs --check   exit 1 if the committed files are stale
//
// Source of truth: slicepoint/schemas/jsonschema/AssessmentResult.schema.json (itself
// generated from the Pydantic models). Three outputs:
//
// 1. assessment-result.generated.ts  TypeScript types (json-schema-to-typescript).
// 2. validate.generated.js           a precompiled Ajv validator (standalone code), so the
//                                     page needs no `eval`/`new Function` and the CSP can
//                                     stay strict.
// 3. schema-meta.generated.ts        the schema_version constant and the schema's sha256.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const schemaPath = resolve(root, "../schemas/jsonschema/AssessmentResult.schema.json");
const outDir = resolve(root, "src/contract");
const check = process.argv.includes("--check");

const schemaText = readFileSync(schemaPath, "utf8");
const schema = JSON.parse(schemaText);
const sha256 = createHash("sha256").update(schemaText).digest("hex");
const source = relative(root, schemaPath);
const banner = (comment) =>
  `${comment} GENERATED by scripts/gen-contract.mjs from ${source} (sha256 ${sha256}).\n` +
  `${comment} Do not edit. Run \`pnpm gen:contract\` after the schema changes; \`pnpm check:contract\` fails on drift.\n`;

// 1. TypeScript types ---------------------------------------------------------------
const types = await compile(schema, "AssessmentResult", {
  bannerComment: banner("//").trimEnd(),
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  format: true,
  style: { singleQuote: false, semi: true, printWidth: 100 },
});

// 2. Precompiled validator ------------------------------------------------------------
const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  strictRequired: false,
  allowUnionTypes: true,
  code: { source: true, esm: true, lines: false },
});
addFormats(ajv, ["date", "date-time"]);
const validate = ajv.compile(schema);
let code = standaloneCode(ajv, validate);
// ajv-formats and ajv's runtime helpers are referenced with require(); make the module pure ESM.
const imports = new Map();
code = code.replace(
  /require\("ajv-formats\/dist\/formats"\)\.fullFormats(?:\.([\w]+)|\["([\w-]+)"\])/g,
  (_m, a, b) => {
    imports.set("fullFormats", `import { fullFormats } from "ajv-formats/dist/formats.js";`);
    return `fullFormats[${JSON.stringify(a ?? b)}]`;
  },
);
code = code.replace(/require\("ajv\/dist\/runtime\/(\w+)"\)\.default/g, (_m, mod) => {
  const name = `runtime_${mod}`;
  imports.set(name, `import ${name} from "ajv/dist/runtime/${mod}.js";`);
  return `(${name}.default ?? ${name})`;
});
if (/\brequire\(/.test(code)) {
  console.error("gen-contract: the standalone validator still contains require(); update the rewrite rules.");
  process.exit(2);
}
if (!/export const validate = /.test(code)) {
  console.error("gen-contract: unexpected standalone output (no named validate export)");
  process.exit(2);
}
code = code.replace(/^"use strict";/, "");
const validator = `${banner("//")}/* eslint-disable */\n${[...imports.values()].join("\n")}\n${code}\n`;
const validatorDts =
  `${banner("//")}import type { AssessmentResult } from "./assessment-result.generated";\n` +
  `export interface ValidationError {\n  instancePath: string;\n  schemaPath: string;\n  keyword: string;\n` +
  `  params: Record<string, unknown>;\n  message?: string;\n}\n` +
  `export interface Validator {\n  (data: unknown): data is AssessmentResult;\n  errors?: ValidationError[] | null;\n}\n` +
  `export declare const validate: Validator;\nexport default validate;\n`;

// 3. Meta -----------------------------------------------------------------------------
const version = schema?.properties?.schema_version?.const;
const resultType = schema?.properties?.result_type?.const;
if (typeof version !== "string" || typeof resultType !== "string") {
  console.error("gen-contract: schema has no schema_version/result_type const");
  process.exit(2);
}
const meta =
  `${banner("//")}export const SCHEMA_VERSION = ${JSON.stringify(version)} as const;\n` +
  `export const RESULT_TYPE = ${JSON.stringify(resultType)} as const;\n` +
  `export const SCHEMA_SHA256 = ${JSON.stringify(sha256)};\n`;

const outputs = {
  "assessment-result.generated.ts": types,
  "validate.generated.js": validator,
  "validate.generated.d.ts": validatorDts,
  "schema-meta.generated.ts": meta,
};

let stale = [];
for (const [name, text] of Object.entries(outputs)) {
  const path = resolve(outDir, name);
  if (check) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== text) stale.push(name);
  } else {
    mkdirSync(outDir, { recursive: true });
    writeFileSync(path, text);
  }
}
if (check) {
  if (stale.length) {
    console.error(
      `Contract drift: ${stale.join(", ")} in src/contract do not match ${source}.\n` +
        "Run `pnpm gen:contract` and review the change (and bump the viewer if schema_version changed).",
    );
    process.exit(1);
  }
  console.log(`Contract up to date (schema_version ${version}, sha256 ${sha256.slice(0, 12)}).`);
} else {
  console.log(`Wrote ${Object.keys(outputs).length} files to ${relative(root, outDir)} (schema_version ${version}).`);
}
